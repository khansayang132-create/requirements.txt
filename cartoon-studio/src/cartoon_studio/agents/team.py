class AgentResult(BaseModel):
    status: str
    artifact_paths: list[str] = []
    metadata: dict = {}
    error: str | None = None
    cost_usd: float = 0.0


UNIVERSE_FILE = "universe-bible.json"   # V3 bible; an owner's own universe.json next to it is never touched


def save_universe(root: Path, u: UniverseBible) -> Path:
    d = root / "universes" / u.universe_id
    if not (d / "universe.json").is_file():
        write_json(d / "universe.json", {"id": u.universe_id, "title": u.title, "premise": u.concept, "tone": u.tone,
                                         "world_rules": u.world_rules, "originality_note": "generated by cartoon-studio"})
    return write_json(d / UNIVERSE_FILE, u)


@dataclass
class Context:
    settings: Settings
    overrides: dict = field(default_factory=dict)

    @property
    def root(self) -> Path:
        return self.settings.root

    def provider(self, name: str):
        return self.overrides.get(name) or get_provider(name, self.settings)

    def universe(self, uid: str) -> UniverseBible:
        p = self.root / "universes" / uid / UNIVERSE_FILE
        if not p.is_file():
            raise ConsistencyError(f"no universe {uid}: run init-universe (or import-universe) first")
        return UniverseBible.model_validate_json(p.read_text(encoding="utf-8"))

    def episode(self, eid: str) -> EpisodeScript:
        return EpisodeScript.model_validate_json((self.root / "stories" / f"{eid}.json").read_text(encoding="utf-8"))

    def engine_cfg(self, state: ProductionState) -> dict:
        engine.load()
        from wonderland import config as wcfg

        cfg = wcfg.load_studio(engine.ROOT)
        t = state.target_seconds
        cfg["video"].update(width=state.resolution[0], height=state.resolution[1], backend=state.backend,
                            min_seconds=max(10.0, t * 0.9 - 1.0), max_seconds=t * 1.1 + 1.5)
        return cfg


class BaseAgent(ABC):
    name = ""
    description = ""

    def __init__(self, ctx: Context | None = None):
        self.ctx = ctx or Context(Settings())

    @abstractmethod
    async def run(self, state: ProductionState) -> AgentResult: ...

    def authorize(self, state: ProductionState, provider, capability: str, amount: float) -> float:
        if not provider.paid:
            return 0.0
        est = provider.estimate_usd(capability, amount)
        if not state.spend_approved:
            raise SpendNotApproved(f"{provider.name} {capability} is paid (estimate {f'${est:.2f}' if est is not None else 'unknown'}); "
                                   "re-run with --approve-spend")
        if est is None:
            raise SpendNotApproved(f"no confirmed price for {provider.name}/{capability} in configuration/pricing.json")
        if state.spent_usd + est > self.ctx.settings.cs_max_spend_usd:
            raise SpendNotApproved(f"{provider.name} {capability} (${est:.2f}) would pass CS_MAX_SPEND_USD")
        return est


class CartoonCreativeDirectorAgent(BaseAgent):
    name = "creative-director"
    description = "Invents the universe: world, rules, tone, places, recurring storylines; runs the originality check."

    def create(self, concept: str, seed: str = "1") -> UniverseBible:
        u = make_universe(concept, seed)
        save_universe(self.ctx.root, u)
        return u

    async def run(self, state):
        u = self.ctx.universe(state.universe_id)
        issues = u.originality.get("issues", [])
        return AgentResult(status="success" if not issues else "failed", metadata={"title": u.title, "characters": [c.name for c in u.characters]},
                           artifact_paths=[str(self.ctx.root / "universes" / u.universe_id / UNIVERSE_FILE)], error="; ".join(issues) or None)


class CharacterDesignerAgent(BaseAgent):
    name = "character-designer"
    description = "Character specs and bibles: front/side/back references, expression, pose and colour sheets, voices, hash locks."

    def design(self, u: UniverseBible, backend: str = "auto") -> dict:
        out = {}
        for c in u.characters:
            out[c.character_id] = bible.render_bible(u, c, self.ctx.root, backend)
        save_universe(self.ctx.root, u)   # now carries the reference hashes
        for c in u.characters:
            write_json(self.ctx.root / "characters" / f"{c.character_id}.json", c)
        return out

    async def run(self, state):
        """Lock the job to the approved bibles: refuse if any bible is missing or changed."""
        u = self.ctx.universe(state.universe_id)
        locked = {}
        for c in u.characters:
            locked[c.character_id] = bible.verify(self.ctx.root, c.character_id, state.character_hashes.get(c.character_id))
        state.character_hashes = locked
        return AgentResult(status="success", metadata={"bibles_verified": len(locked)})


class StoryWriterAgent(BaseAgent):
    name = "story-writer"
    description = "Original seven-act episode (hook to ending) checked by the child-safety review and the originality check."

    def write(self, uid: str, plot: str | None = None, seed: str = "1", target_seconds: int = 60) -> EpisodeScript:
        e = write_episode(self.ctx.universe(uid), plot, seed, target_seconds)
        write_json(self.ctx.root / "stories" / f"{e.episode_id}.json", e)
        (self.ctx.root / "scripts" / f"{e.episode_id}.txt").write_text(
            "\n".join(f"[{s.act}] {s.dialogue['speaker']}: {s.dialogue['text']}" for s in e.scenes), encoding="utf-8")
        return e

    async def run(self, state):
        e = self.ctx.episode(state.episode_id)
        return AgentResult(status="success", metadata={"title": e.title, "acts": sorted({s.act for s in e.scenes}), "scenes": len(e.scenes)})


class StoryboardArtistAgent(BaseAgent):
    name = "storyboard-artist"
    description = "Shot list: per scene duration, location, cast, actions, dialogue, camera, lighting, sound, music, transition."

    async def run(self, state):
        e = self.ctx.episode(state.episode_id)
        out = write_json(self.ctx.root / "storyboards" / f"{e.episode_id}.json", {"episode": e.episode_id, "scenes": [s.model_dump() for s in e.scenes]})
        return AgentResult(status="success", artifact_paths=[str(out)], metadata={"shots": len(e.scenes)})


class _EngineMixin:
    def prepared(self, state):
        engine.load()
        from wonderland import pipeline as wp

        e = self.ctx.episode(state.episode_id)
        u = self.ctx.universe(state.universe_id)
        cfg = self.ctx.engine_cfg(state)
        desk = wp.make_desk(cfg, self.ctx.root / "voices")
        story = {"title": e.title, "summary": e.logline, "learning_goal": e.moral, "beats": e.beats, "mood": "bright", "song": False}
        return wp, wp.prepare(story, engine_universe(u), cfg, desk, salt=state.job_id), story, engine_universe(u), cfg

    def work(self, state) -> Path:
        d = self.ctx.root / "scenes" / state.job_id
        d.mkdir(parents=True, exist_ok=True)
        return d


class VoiceSoundEngineerAgent(BaseAgent, _EngineMixin):
    name = "voice-sound-engineer"
    description = "Character voices (Kokoro/eSpeak locally, ElevenLabs when configured), timings, Foley, ambience, music, mix."

    async def run(self, state):
        wp, prep, *_ = await asyncio.to_thread(self.prepared, state)
        out = wp.stage_storyboard(self.work(state), prep)
        state.voice_manifest = {"providers": out["voice_providers"], "lines": out["voice_lines"], "seconds": out["timing"]["total_seconds"]}
        return AgentResult(status="success", metadata=state.voice_manifest, artifact_paths=[str(self.work(state) / "storyboard.json")])

    async def mix(self, state):
        wp, prep, story, uni, cfg = await asyncio.to_thread(self.prepared, state)
        out = await asyncio.to_thread(wp.stage_sound, self.work(state), prep, story, uni, cfg)
        sfx = self.ctx.root / "sound-effects" / f"{state.job_id}-foley.json"
        sfx.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(self.work(state) / "foley.json", sfx)
        return AgentResult(status="success", artifact_paths=[out["path"], str(sfx)],
                           metadata={k: out.get(k) for k in ("seconds", "voice_providers", "voice_to_bed_db", "foley_events")})


class AnimationEngineerAgent(BaseAgent, _EngineMixin):
    name = "animation-engineer"
    description = "Animates the characters: 3D toon (Three.js) or 2D rig locally; Blender when installed."

    async def backgrounds(self, state):
        engine.load()
        from wonderland.render.environments import background

        e = self.ctx.episode(state.episode_id)
        d = self.work(state) / "backgrounds"
        d.mkdir(exist_ok=True)
        paths = []
        for env in sorted({s.environment for s in e.scenes}):
            p = d / f"{env}.png"
            background(env, 1).convert("RGB").resize(state.resolution).save(p)
            paths.append(str(p))
        return AgentResult(status="success", artifact_paths=paths)

    async def run(self, state):
        wp, prep, _story, uni, cfg = await asyncio.to_thread(self.prepared, state)
        out = await asyncio.to_thread(wp.stage_animation, self.work(state), prep, uni, cfg)
        dst = self.ctx.root / "animations" / f"{state.job_id}-silent.mp4"
        dst.parent.mkdir(parents=True, exist_ok=True)   # git-ignored, so absent in a fresh checkout
        shutil.copyfile(self.work(state) / "silent.mp4", dst)
        return AgentResult(status="success", artifact_paths=[str(dst)],
                           metadata={k: out.get(k) for k in ("frames", "render_seconds", "backend", "backend_reason")})


class VideoGenerationEngineerAgent(BaseAgent):
    name = "video-generation-engineer"
    description = "Optional extra shots from external image-to-video (Runway, Kling, Higgsfield), conditioned on the bible reference."

    async def run(self, state):
        if state.video_provider == "none":
            return AgentResult(status="skipped", metadata={"reason": "no external video provider selected; the episode is rendered by the local engine"})
        prov = self.ctx.provider(state.video_provider)
        prov.key()
        est = 0.0 if state.paid_jobs.get("video") else self.authorize(state, prov, "video", 5)
        e = self.ctx.episode(state.episode_id)
        lead = e.originality.get("cast", [None])[0]
        ref = self.ctx.root / "character-bibles" / lead / "reference_front.png"
        out = self.ctx.root / "scenes" / state.job_id / "external_shot.mp4"
        res = await asyncio.to_thread(prov.image_to_video, ref, f"{e.title}: gentle cartoon motion, soft light", out,
                                      5, state.paid_jobs.get("video"))
        state.paid_jobs["video"] = res["job_id"]
        state.video_clips.append(res["video"])
        return AgentResult(status="success", artifact_paths=[res["video"]], cost_usd=est, metadata={"provider": prov.name})


class CinematicEditorAgent(BaseAgent, _EngineMixin):
    name = "cinematic-editor"
    description = "Assembly with FFmpeg: picture + mix, captions, cover, contact sheet, loudness; export MP4."

    async def run(self, state):
        wp, prep, *_ , cfg = await asyncio.to_thread(self.prepared, state)
        await asyncio.to_thread(wp.stage_edit, self.work(state), prep, cfg)
        dst = self.ctx.root / "rendered-videos" / state.job_id
        dst.mkdir(parents=True, exist_ok=True)
        for f in ("final.mp4", "final.srt", "sheet.png", "cover.png"):
            shutil.copyfile(self.work(state) / f, dst / f)
        state.final_video = str(dst / "final.mp4")
        return AgentResult(status="success", artifact_paths=[str(dst / f) for f in ("final.mp4", "final.srt", "sheet.png")])


class QualityControlAgent(BaseAgent, _EngineMixin):
    name = "quality-control"
    description = "ffprobe/ffmpeg checks, target duration ±10 %, lip-sync track, bible hashes unchanged; PASS/FAIL/BLOCKED/NOT_TESTED."

    async def run(self, state):
        wp, prep, *_, cfg = await asyncio.to_thread(self.prepared, state)
        rep = await asyncio.to_thread(wp.stage_qa, self.work(state), prep, cfg)
        checks = {c["name"]: {"status": "PASS" if c["passed"] else "FAIL", "detail": c["detail"]} for c in rep["checks"]}
        dur = rep["metrics"]["duration"]
        t = state.target_seconds
        checks["target_duration"] = {"status": "PASS" if abs(dur - t) <= 0.1 * t else "FAIL", "detail": f"{dur:.1f}s (target {t}s ±10%)"}
        checks["lip_sync_track"] = {"status": "PASS" if rep["sync"]["ok"] else "FAIL", "detail": f"worst drift {rep['sync']['worst_drift_seconds']}s"}
        try:
            u = self.ctx.universe(state.universe_id)
            for c in u.characters:
                bible.verify(self.ctx.root, c.character_id, state.character_hashes.get(c.character_id))
            checks["character_reference_hashes"] = {"status": "PASS", "detail": f"{len(u.characters)} bibles match the hashes locked at job start"}
        except ConsistencyError as e:
            checks["character_reference_hashes"] = {"status": "FAIL", "detail": str(e)}
        checks["visual_identity_review"] = {"status": "NOT_TESTED", "detail": "look at sheet.png: automatic face matching is not installed"}
        overall = "FAIL" if any(v["status"] == "FAIL" for v in checks.values()) else "PASS"
        out = Path(state.final_video).parent / "qc_report.json" if state.final_video else self.work(state) / "qc_report.json"
        out.write_text(json.dumps({"overall": overall, "checks": checks, "metrics": rep["metrics"]}, indent=2), encoding="utf-8")
        state.qc_status = overall
        return AgentResult(status="success" if overall == "PASS" else "failed", artifact_paths=[str(out)], metadata={"overall": overall},
                           error=None if overall == "PASS" else ", ".join(k for k, v in checks.items() if v["status"] == "FAIL"))


class ProductionManagerAgent(BaseAgent):
    name = "production-manager"
    description = "Runs the 13-step graph, enforces the spend gate and bible locks, resumes jobs, reports."

    async def analyze(self, state):
        e = self.ctx.episode(state.episode_id)
        return AgentResult(status="success", metadata={"scenes": len(e.scenes), "acts": [s.act for s in e.scenes]})

    async def export(self, state):
        return AgentResult(status="success", artifact_paths=[state.final_video], metadata={"final_video": state.final_video, "qc": state.qc_status})

    async def run(self, state):
        from ..pipeline import run_graph

        agents = {cls.name: cls(self.ctx) for cls in ALL_AGENTS if cls is not ProductionManagerAgent}
        agents[self.name] = self
        path = self.ctx.root / "jobs" / state.job_id / "state.json"
        await run_graph(state, agents, lambda s: s.save(path))
        rep = {"job_id": state.job_id, "final_video": state.final_video if state.steps.get("13_export") and state.steps["13_export"].status == "success" else None,
               "qc": state.qc_status, "spent_usd": state.spent_usd,
               "steps": {k: v.model_dump() for k, v in state.steps.items()}}
        out = self.ctx.root / "jobs" / state.job_id / "production_report.json"
        out.write_text(json.dumps(rep, indent=2), encoding="utf-8")
        return AgentResult(status="success" if rep["final_video"] else "blocked", artifact_paths=[str(out)], metadata=rep)


ALL_AGENTS = [CartoonCreativeDirectorAgent, CharacterDesignerAgent, StoryWriterAgent, StoryboardArtistAgent, AnimationEngineerAgent,
              VideoGenerationEngineerAgent, VoiceSoundEngineerAgent, CinematicEditorAgent, QualityControlAgent, ProductionManagerAgent]

AGENTS = ALL_AGENTS   # v0.3 name
